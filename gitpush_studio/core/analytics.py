def _digest(data):
    return hashlib.blake2b(data, digest_size=16).digest()


_OPEN_FLAGS = (os.O_RDONLY | getattr(os, "O_BINARY", 0)
               | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0))


def _hash_file(path, limit=None, chunk=1 << 20):
    """Hash de los primeros `limit` bytes (o del archivo entero), o None.

    Solo de un ARCHIVO NORMAL y sin seguir enlaces: un enlace del
    proyecto a /dev/tty, /dev/stdin o una tubería dejaba el análisis
    esperando para siempre (sin poder detenerlo), y uno a un archivo de
    fuera lo leía para compararlo."""
    h = hashlib.blake2b(digest_size=16)
    leidos = 0
    try:
        if stat.S_ISLNK(os.lstat(path).st_mode):
            return None                   # sin O_NOFOLLOW (Windows), también
        fd = os.open(path, _OPEN_FLAGS)
    except OSError:
        return None
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            return None
        fh = os.fdopen(fd, "rb")
        fd = None
        with fh:
            while True:
                pide = chunk if limit is None else min(chunk, limit - leidos)
                if pide <= 0:
                    break
                trozo = fh.read(pide)
                if not trozo:
                    break
                h.update(trozo)
                leidos += len(trozo)
    except OSError:
        return None
    finally:
        if fd is not None:
            os.close(fd)
    return h.digest()


def find_duplicates(items, cancel=None):
    """Grupos de archivos idénticos.

    `items`: [(rel, ruta, tamaño, hash_cabeza|None, hash_completo|None)].
    Los hashes que ya se tienen (archivos leídos para contar líneas) se
    usan; los que faltan se calculan solo para los candidatos.
    """
    por_tamano = defaultdict(list)
    for it in items:
        if it[2] > 0:
            por_tamano[it[2]].append(it)
    grupos = []
    for size, cands in por_tamano.items():
        if len(cands) < 2:
            continue
        por_cabeza = defaultdict(list)
        for rel, ruta, _s, cabeza, completo in cands:
            if cancel is not None and cancel.is_set():
                raise Cancelled("Análisis detenido.")
            if cabeza is None:
                cabeza = _hash_file(ruta, HEAD_BYTES)
            if cabeza is not None:
                por_cabeza[cabeza].append((rel, ruta, completo))
        for misma in por_cabeza.values():
            if len(misma) < 2:
                continue
            if size <= HEAD_BYTES:
                # La cabeza ya ES el archivo entero.
                grupos.append(DuplicateGroup(size,
                                             sorted(r for r, _, _ in misma)))
                continue
            por_completo = defaultdict(list)
            for rel, ruta, completo in misma:
                if completo is None:
                    completo = _hash_file(ruta)
                if completo is not None:
                    por_completo[completo].append(rel)
            for rels in por_completo.values():
                if len(rels) > 1:
                    grupos.append(DuplicateGroup(size, sorted(rels)))
    grupos.sort(key=lambda g: (-g.wasted, g.paths[0]))
    return grupos


