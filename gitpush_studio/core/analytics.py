@dataclass
class FileInfo:
    rel: str
    size: int
    language: str = ""            # "" en los binarios
    kind: str = BINARY
    code: int = 0
    comment: int = 0
    blank: int = 0
    generated: str = ""           # motivo, o "" si es propio
    note: str = ""                # «demasiado grande», «ilegible»…

    @property
    def lines(self):
        return self.code + self.comment + self.blank


@dataclass
class LanguageSummary:
    name: str
    kind: str
    files: int = 0
    code: int = 0
    comment: int = 0
    blank: int = 0
    bytes: int = 0

    @property
    def lines(self):
        return self.code + self.comment + self.blank

    @property
    def comment_ratio(self):
        base = self.code + self.comment
        return self.comment / base if base else 0.0


@dataclass
class DuplicateGroup:
    size: int
    paths: list

    @property
    def wasted(self):
        return self.size * (len(self.paths) - 1)


@dataclass
class Marker:
    rel: str
    line: int
    kind: str
    text: str


@dataclass
class ProjectReport:
    root: str
    name: str
    generated_at: str = ""
    seconds: float = 0.0
    files: list = field(default_factory=list)            # [FileInfo]
    ignored: int = 0
    languages: list = field(default_factory=list)        # propios
    generated_languages: list = field(default_factory=list)
    binary_groups: list = field(default_factory=list)    # [(grupo, n, bytes)]
    duplicates: list = field(default_factory=list)       # [DuplicateGroup]
    duplicate_groups_total: int = 0
    wasted_bytes: int = 0
    markers: dict = field(default_factory=dict)          # tipo → cuántas
    marker_samples: list = field(default_factory=list)   # [Marker]
    histogram: list = field(default_factory=list)        # [(etiqueta, n, b)]
    git: object = None                                    # GitReport | None

    # ---- totales derivados -------------------------------------------
    @property
    def total_files(self):
        return len(self.files)

    @property
    def total_bytes(self):
        return sum(f.size for f in self.files)

    def own(self):
        return [f for f in self.files if not f.generated]

    def lines_by_kind(self, generated=False):
        """{tipo: LineCounts} del código propio (o del generado)."""
        out = {k: LineCounts() for k in KINDS}
        for f in self.files:
            if f.kind in out and bool(f.generated) == generated:
                out[f.kind].add(LineCounts(f.code, f.comment, f.blank))
        return out

    def largest(self, n=TOP_N):
        return heapq.nlargest(n, self.files, key=lambda f: (f.size, f.rel))

    def longest(self, n=TOP_N):
        """Los archivos propios con más líneas de código."""
        return heapq.nlargest(n, (f for f in self.files if not f.generated
                                  and f.kind != BINARY),
                              key=lambda f: (f.code, f.rel))

    def generated_files(self):
        return [f for f in self.files if f.generated]

    def unreadable(self):
        return [f for f in self.files if f.note]

    @property
    def depth(self):
        return max((f.rel.count("/") + 1 for f in self.files), default=0)

    def to_dict(self, include_files=True):
        """Todo en tipos de JSON, listo para `json.dump`."""
        def lc(c):
            return {"code": c.code, "comment": c.comment, "blank": c.blank}

        d = {
            "root": self.root, "name": self.name,
            "generated_at": self.generated_at,
            "seconds": round(self.seconds, 3),
            "files": self.total_files, "bytes": self.total_bytes,
            "ignored": self.ignored, "depth": self.depth,
            "own": {k: lc(v) for k, v in self.lines_by_kind().items()},
            "generated": {k: lc(v) for k, v in
                          self.lines_by_kind(True).items()},
            "languages": [dict(l.__dict__, lines=l.lines,
                               comment_ratio=round(l.comment_ratio, 4))
                          for l in self.languages],
            "generated_languages": [dict(l.__dict__, lines=l.lines)
                                    for l in self.generated_languages],
            "binary_groups": [{"group": g, "files": n, "bytes": b}
                              for g, n, b in self.binary_groups],
            "largest": [{"path": f.rel, "bytes": f.size}
                        for f in self.largest()],
            "longest": [{"path": f.rel, "code": f.code}
                        for f in self.longest()],
            "duplicates": [{"size": g.size, "wasted": g.wasted,
                            "paths": g.paths} for g in self.duplicates],
            "duplicate_groups_total": self.duplicate_groups_total,
            "wasted_bytes": self.wasted_bytes,
            "markers": dict(self.markers),
            "marker_samples": [m.__dict__ for m in self.marker_samples],
            "histogram": [{"range": e, "files": n, "bytes": b}
                          for e, n, b in self.histogram],
            "git": self.git.to_dict() if self.git is not None else None,
        }
        if include_files:
            d["file_list"] = [dict(f.__dict__) for f in self.files]
        return d


