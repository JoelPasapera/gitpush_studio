def _pct(parte, todo):
    return "%.0f %%" % (100.0 * parte / todo) if todo else "—"


def _n(x):
    """12345 → «12.345». Solo el número: formatear la frase entera
    convertiría también sus comas en puntos."""
    return "{:,}".format(x).replace(",", ".")


def summary_lines(rep, top=8):
    """El informe en líneas de texto plano: lo usan la CLI y la consola."""
    out = []
    propio = rep.lines_by_kind()
    generado = rep.lines_by_kind(True)
    codigo = propio[CODE]
    out.append(f"PROYECTO {rep.name} · {_n(rep.total_files)} archivos · "
               f"{fmt_size(rep.total_bytes)} · analizado en "
               f"{rep.seconds:.1f} s")
    out.append(f"Código propio: {_n(codigo.code)} líneas de código, "
               f"{_n(codigo.comment)} de comentario "
               f"({_pct(codigo.comment, codigo.code + codigo.comment)}), "
               f"{_n(codigo.blank)} en blanco")
    otros = [(k, propio[k].code) for k in (MARKUP, DATA, PROSE)
             if propio[k].code]
    if otros:
        out.append("Además: " + " · ".join(f"{_n(n)} de {k}"
                                           for k, n in otros))
    gen = sum(c.total for c in generado.values())
    if gen:
        out.append(f"Generado o de terceros (no cuenta como propio): "
                   f"{_n(len(rep.generated_files()))} archivos, "
                   f"{_n(gen)} líneas")
    if rep.languages:
        out.append("")
        out.append("LENGUAJES (código propio)")
        total_code = sum(l.code for l in rep.languages) or 1
        for l in rep.languages[:top]:
            out.append(f"  {l.name:<22} {_n(l.files):>6} arch. "
                       f"{_n(l.code):>10} código  "
                       f"{_pct(l.code, total_code):>5}")
        resto = rep.languages[top:]
        if resto:
            out.append(f"  … y {len(resto)} más")
    if rep.binary_groups:
        out.append("")
        out.append("BINARIOS")
        for g, n, b in rep.binary_groups:
            out.append(f"  {g:<26} {_n(n):>6} arch. {fmt_size(b):>9}")
    if rep.duplicate_groups_total:
        out.append("")
        out.append(f"DUPLICADOS: {_n(rep.duplicate_groups_total)} grupos, "
                   f"{fmt_size(rep.wasted_bytes)} repetidos")
        for g in rep.duplicates[:5]:
            out.append(f"  {len(g.paths)} × {fmt_size(g.size)}: "
                       + ", ".join(g.paths[:3])
                       + (" …" if len(g.paths) > 3 else ""))
    if rep.markers:
        out.append("")
        out.append("PENDIENTES: " + " · ".join(
            f"{k} {_n(v)}" for k, v in sorted(rep.markers.items(),
                                             key=lambda kv: -kv[1])))
    raros = rep.unreadable()
    if raros:
        out.append("")
        out.append(f"SIN CONTAR: {_n(len(raros))} archivos (muy grandes o "
                   "ilegibles)")
    if rep.git is not None:
        g = rep.git
        out.append("")
        desde = datetime.fromtimestamp(g.first).strftime("%Y-%m-%d")
        hasta = datetime.fromtimestamp(g.last).strftime("%Y-%m-%d")
        out.append(f"HISTORIAL: {_n(g.commits)} commits de "
                   f"{_n(len(g.authors))} personas, del {desde} al {hasta}")
        out.append(f"  Factor bus: {g.bus_factor} (cuántas personas suman "
                   "más de la mitad de los commits)")
        for a in g.authors[:5]:
            out.append(f"  {a.name:<24} {_n(a.commits):>6} commits  "
                       f"+{_n(a.added)} −{_n(a.deleted)}")
        if g.churn:
            out.append("  Lo que más se toca:")
            for c in g.churn[:5]:
                marca = "" if c.exists else "  (ya no existe)"
                out.append(f"    {_n(c.commits):>4} × {c.path}{marca}")
        if g.truncated:
            out.append("  (historial recortado a los últimos commits)")
        if g.shallow:
            out.append("  (copia ligera: el historial está incompleto)")
    return out
