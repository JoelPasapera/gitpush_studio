def _scan_markers(rel, buf, contadores, muestras):
    linea, desde = 1, 0
    for m in _MARKERS.finditer(buf):
        tipo = m.group(1).decode("ascii")
        contadores[tipo] = contadores.get(tipo, 0) + 1
        if len(muestras) < MAX_MARKER_SAMPLES:
            linea += buf.count(b"\n", desde, m.start())
            desde = m.start()
            texto = m.group(2).decode("utf-8", "replace").strip()
            muestras.append(Marker(rel, linea, tipo, texto[:100]))


def _classify(rel, size, raw):
    """FileInfo (+ hashes) de un archivo leído entero en memoria."""
    if raw and looks_binary(raw) and not is_utf16(raw):
        return FileInfo(rel, size, "", BINARY), None
    texto = normalize_text(raw)
    nombre = detect(rel, texto[:256]) or UNKNOWN_TEXT
    lang = get(nombre)
    cuenta = count_lines(texto, lang)
    motivo = generated_reason(rel, texto[:2048],
                              average_line_length(texto), size)
    return (FileInfo(rel, size, lang.name, lang.kind, cuenta.code,
                     cuenta.comment, cuenta.blank, motivo), texto)


def _summaries(files, generated):
    tabla = {}
    for f in files:
        if f.kind == BINARY or bool(f.generated) != generated:
            continue
        s = tabla.get(f.language)
        if s is None:
            s = tabla[f.language] = LanguageSummary(f.language,
                                                    get(f.language).kind)
        s.files += 1
        s.code += f.code
        s.comment += f.comment
        s.blank += f.blank
        s.bytes += f.size
    return sorted(tabla.values(), key=lambda s: (-s.code, -s.lines, s.name))


def _histogram(files):
    filas = []
    for lo, hi, etiqueta in _HISTOGRAM:
        sel = [f.size for f in files if lo <= f.size <= hi]
        filas.append((etiqueta, len(sel), sum(sel)))
    return filas


def _binary_groups(files):
    tabla = defaultdict(lambda: [0, 0])
    for f in files:
        if f.kind == BINARY:
            g = binary_group(f.rel)
            tabla[g][0] += 1
            tabla[g][1] += f.size
    return sorted(((g, n, b) for g, (n, b) in tabla.items()),
                  key=lambda t: (-t[2], t[0]))


def analyze_project(folder, extra_patterns=(), respect_ignores=True,
                    use_git=True, history=True, on_progress=None,
                    cancel=None, max_file_bytes=ANALYZE_MAX_FILE):
    """`ProjectReport` de la carpeta. Lanza `Cancelled` si se detiene."""
    t0 = time.time()
    root = Path(folder).resolve()
    entries, ignorados = project_entries(root, extra_patterns,
                                         respect_ignores=respect_ignores,
                                         use_git=use_git)
    total = len(entries)
    rutas = {rel: path for rel, path, _ in entries}
    files, para_duplicados = [], []
    contadores, muestras = {}, []

    def avisa(hechos, rel):
        if on_progress is not None and (hechos % 200 == 0
                                        or hechos == total):
            on_progress(hechos, total, rel)

    for hechos, (rel, size, raw) in enumerate(
            iter_payloads(entries, max_file_bytes), 1):
        if cancel is not None and cancel.is_set():
            raise Cancelled("Análisis detenido.")
        cabeza = completo = None
        if isinstance(raw, Exception):
            info = FileInfo(rel, size, "", BINARY,
                            note="no se pudo leer: %s" % raw)
        elif isinstance(raw, Link):
            info = FileInfo(rel, size, "", BINARY,
                            note="enlace simbólico (no se sigue)")
        elif isinstance(raw, Special):
            info = FileInfo(rel, size, "", BINARY, note=str(raw))
        elif raw is None:
            if is_binary_ext(rel):
                info = FileInfo(rel, size, "", BINARY)
            else:
                info = FileInfo(rel, size, "", BINARY,
                                note="demasiado grande para contar líneas "
                                     "(%s)" % fmt_size(size))
        else:
            info, texto = _classify(rel, size, raw)
            cabeza = _digest(raw[:HEAD_BYTES])
            if len(raw) == size:
                completo = _digest(raw)
            if texto is not None and not info.generated:
                _scan_markers(rel, texto, contadores, muestras)
        files.append(info)
        if not isinstance(raw, (Exception, Link, Special)):
            # Un enlace no es contenido, y lo que no se pudo abrir no se
            # vuelve a intentar al buscar duplicados.
            para_duplicados.append((rel, rutas.get(rel, ""), size, cabeza,
                                    completo))
        avisa(hechos, rel)

    files.sort(key=lambda f: f.rel.lower())
    duplicados = find_duplicates(para_duplicados, cancel)
    rep = ProjectReport(
        root=str(root), name=root.name,
        generated_at=datetime.now().strftime("%Y-%m-%d %H:%M"),
        files=files, ignored=ignorados,
        languages=_summaries(files, False),
        generated_languages=_summaries(files, True),
        binary_groups=_binary_groups(files),
        duplicates=duplicados[:MAX_DUPLICATE_GROUPS],
        duplicate_groups_total=len(duplicados),
        wasted_bytes=sum(g.wasted for g in duplicados),
        markers=contadores, marker_samples=muestras,
        histogram=_histogram(files))
    if history:
        if cancel is not None and cancel.is_set():
            raise Cancelled("Análisis detenido.")
        rep.git = analyze_history(str(root),
                                  existing={f.rel for f in files},
                                  cancel=cancel)
    rep.seconds = time.time() - t0
    return rep


