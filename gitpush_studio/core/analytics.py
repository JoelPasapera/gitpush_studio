ANALYZE_MAX_FILE = 8 * MB        # texto mayor no se clasifica línea a línea
HEAD_BYTES = 64 * 1024           # primera fase de los duplicados
TOP_N = 15
MAX_MARKER_SAMPLES = 300
MAX_DUPLICATE_GROUPS = 60
BINARY = "binario"
KINDS = (CODE, MARKUP, DATA, PROSE)

# --- Generado o de terceros -----------------------------------------------
_VENDOR_DIRS = frozenset({
    "node_modules", "vendor", "third_party", "third-party",
    "bower_components", "dist", ".yarn", "__generated__", "generated",
    "pods", "carthage", "site-packages", ".venv", "venv",
})
_LOCKFILES = frozenset({
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock",
    "pnpm-lock.yaml", "cargo.lock", "poetry.lock", "pipfile.lock",
    "composer.lock", "gemfile.lock", "go.sum", "packages.lock.json",
    "flake.lock", "uv.lock", "bun.lockb", "mix.lock", "pubspec.lock",
})
_GENERATED_SUFFIXES = (".min.js", ".min.css", "-min.js", ".bundle.js",
                       ".js.map", ".css.map", "_pb2.py", "_pb2_grpc.py",
                       ".pb.go", ".g.dart", ".freezed.dart", ".designer.cs",
                       ".generated.cs", ".g.cs")
# Los generadores lo DECLARAN en un comentario en las primeras líneas
# («// Code generated … DO NOT EDIT.», «# Generated by Django…»,
# «/* @generated */»). Buscar la frase en cualquier sitio marcaría como
# generado un archivo que solo la menciona, como este mismo.
_GENERATED_PHRASE = re.compile(
    rb"@generated|DO NOT EDIT|auto-?generated|automatically generated|"
    rb"generated by|this file (?:is|was) generated", re.IGNORECASE)
_COMMENT_LEADERS = (b"//", b"#", b"/*", b"<!--", b"--", b";", b"%",
                    b'"""', b"'''")
_GENERATED_HEAD_LINES = 6
_MINIFIED_AVG = 300              # bytes por línea a partir de los cuales
_MINIFIED_MIN_SIZE = 2048        # un archivo de texto es minificado

_MARKERS = re.compile(
    rb"\b(TODO|FIXME|HACK|XXX|BUG)\b[ \t]*[:(\-]?[ \t]*([^\r\n]{0,100})")

_HISTOGRAM = ((0, 0, "vacíos"), (1, 1023, "< 1 KB"),
              (1024, 10 * 1024 - 1, "1–10 KB"),
              (10 * 1024, 100 * 1024 - 1, "10–100 KB"),
              (100 * 1024, MB - 1, "100 KB–1 MB"),
              (MB, 10 * MB - 1, "1–10 MB"),
              (10 * MB, float("inf"), "> 10 MB"))


def _header_says_generated(head):
    """¿Una de las primeras líneas es un COMENTARIO que lo declara?

    Un « * » solo cuenta como comentario si antes se abrió un «/*»: en
    un docstring de Python es una viñeta, y la frase que la sigue habla
    de otra cosa.
    """
    en_bloque = False
    for linea in head[:2048].split(b"\n")[:_GENERATED_HEAD_LINES]:
        t = linea.lstrip()
        if t.startswith(b"/*"):
            en_bloque = True
        lider = t.startswith(_COMMENT_LEADERS) or (en_bloque
                                                   and t.startswith(b"*"))
        if lider and _GENERATED_PHRASE.search(t):
            return True
        if b"*/" in t:
            en_bloque = False
    return False


def generated_reason(rel, head=b"", avg_line=0.0, size=0):
    """Por qué un archivo parece generado o de terceros ("" si no)."""
    low = rel.lower()
    partes = low.split("/")
    for carpeta in partes[:-1]:
        if carpeta in _VENDOR_DIRS:
            return f"carpeta «{carpeta}»"
    nombre = partes[-1]
    if nombre in _LOCKFILES:
        return "archivo de bloqueo de dependencias"
    for suf in _GENERATED_SUFFIXES:
        if nombre.endswith(suf):
            return f"«{suf}»"
    if head and _header_says_generated(head):
        return "cabecera de archivo generado"
    if size >= _MINIFIED_MIN_SIZE and avg_line >= _MINIFIED_AVG:
        return "minificado (líneas de %d bytes de media)" % avg_line
    return ""


