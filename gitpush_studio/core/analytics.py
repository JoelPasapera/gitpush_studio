# -*- coding: utf-8 -*-
"""Analíticas de un proyecto entero: de qué está hecho y cómo está.

Una pasada sobre los archivos (los mismos que se publicarían: respeta el
.gitignore y el cuadro de ignorar) que reúne:

  · lenguajes y líneas de código / comentario / en blanco (`linecount`);
  · código propio frente a código generado o de terceros (dependencias
    copiadas, archivos de bloqueo, minificados, cabeceras «@generated»):
    un `node_modules` subido por error no puede inflar «tu» código;
  · tamaños: los más grandes, el reparto por tramos y por tipo binario;
  · archivos duplicados, en dos fases: primero se agrupan por tamaño
    (solo dos archivos del mismo tamaño pueden ser iguales), dentro de
    cada grupo se compara el hash de los primeros 64 KB, y solo donde
    eso coincide se calcula el hash completo. Lo que ya se leyó para
    contar líneas no se vuelve a leer;
  · marcas pendientes (TODO, FIXME, HACK, XXX, BUG) con su línea;
  · el historial de git, si lo hay (`gitstats`).

Nada sale del equipo: no hay red en todo el módulo.
"""

