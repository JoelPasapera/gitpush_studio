# -*- coding: utf-8 -*-
"""Analíticas del proyecto (core.analytics y core.languages).

Lo que se defiende:
  · cada archivo cae en su lenguaje (extensión, nombre, «#!»);
  · lo generado o de terceros se separa de lo propio, y un archivo que
    solo MENCIONA «@generated» no pasa por generado (le pasó a este mismo
    módulo);
  · los duplicados son idénticos byte a byte: dos archivos con los mismos
    primeros 64 KB y distinto final NO lo son;
  · los totales cuadran (cada archivo en un tramo de tamaño, cada línea
    en una clase) y las marcas TODO llevan su línea exacta;
  · lo ignorado no se cuenta, y se puede detener a mitad.
"""

import json
import os
import shutil
import tempfile
import threading
import unittest
from pathlib import Path

from gitpush_studio.core import analytics
from gitpush_studio.core.analytics import (HEAD_BYTES, analyze_project,
                                           find_duplicates, generated_reason,
                                           summary_lines)
from gitpush_studio.core.errors import Cancelled
from gitpush_studio.core.languages import (LANGS, binary_group, detect,
                                           language_from_shebang)


def write(root, rel, data):
    p = Path(root) / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data if isinstance(data, bytes) else data.encode("utf-8"))
    return p


class LanguageDetectionTests(unittest.TestCase):

    def test_by_extension(self):
        casos = {"a.py": "Python", "b.TS": "TypeScript", "c.mq5": "MQL",
                 "d.wgsl": "WGSL", "e.tex": "LaTeX", "f.ps1": "PowerShell",
                 "g.h": "C", "h.hpp": "C++", "i.yml": "YAML",
                 "j.jsonc": "JSON con comentarios", "k.vue": "Vue"}
        for rel, esperado in casos.items():
            self.assertEqual(detect(rel), esperado, rel)

    def test_by_exact_name(self):
        casos = {"Makefile": "Makefile", "sub/Dockerfile": "Dockerfile",
                 "Dockerfile.prod": "Dockerfile", ".gitignore": "Git",
                 "CMakeLists.txt": "CMake", ".env": "Variables de entorno",
                 ".env.local": "Variables de entorno",
                 ".env.production": "Variables de entorno"}
        for rel, esperado in casos.items():
            self.assertEqual(detect(rel), esperado, rel)

    def test_by_shebang_only_without_a_known_extension(self):
        self.assertEqual(detect("bin/tool", b"#!/usr/bin/env python3\n"),
                         "Python")
        self.assertEqual(detect("run", b"#!/bin/bash\nset -e\n"), "Shell")
        self.assertEqual(detect("x", b"#!/usr/bin/python3.12\n"), "Python")
        self.assertEqual(detect("x", b"#! /usr/bin/env node\n"),
                         "JavaScript")
        # La extensión manda: un .txt con «#!» sigue siendo texto.
        self.assertEqual(detect("notas.txt", b"#!/bin/sh\n"), "Texto")
        self.assertIsNone(detect("x", b"#!/usr/bin/desconocido\n"))
        self.assertIsNone(language_from_shebang(b"sin shebang"))

    def test_unknown_is_none(self):
        self.assertIsNone(detect("archivo.raro"))
        self.assertIsNone(detect("SIN_EXTENSION"))

    def test_binary_groups(self):
        self.assertEqual(binary_group("a/b.PNG"), "Imágenes")
        self.assertEqual(binary_group("x.woff2"), "Fuentes")
        self.assertEqual(binary_group("x.wasm"), "Ejecutables y bibliotecas")
        self.assertEqual(binary_group("x.qwerty"), "Otros binarios")

    def test_every_extension_points_to_a_real_language(self):
        from gitpush_studio.core.languages import EXTENSIONS, FILENAMES
        for ext, nombre in list(EXTENSIONS.items()) + list(FILENAMES.items()):
            self.assertIn(nombre, LANGS, ext)


class GeneratedTests(unittest.TestCase):

    def test_vendored_folders_lockfiles_and_suffixes(self):
        self.assertIn("node_modules", generated_reason("web/node_modules/x.js"))
        self.assertIn("vendor", generated_reason("vendor/lib/a.go"))
        self.assertIn("bloqueo", generated_reason("package-lock.json"))
        self.assertIn("bloqueo", generated_reason("sub/Cargo.lock"))
        self.assertIn(".min.js", generated_reason("static/app.min.js"))
        self.assertIn("_pb2.py", generated_reason("api/user_pb2.py"))
        self.assertEqual(generated_reason("src/app.js"), "")
        # «vendors.py» o «distance.c» no son carpetas de terceros.
        self.assertEqual(generated_reason("vendors.py"), "")
        self.assertEqual(generated_reason("src/distance.c"), "")

    def test_a_generator_header_in_a_comment(self):
        for cabecera in (b"// Code generated by protoc-gen-go. DO NOT EDIT.\n",
                         b"# Generated by Django 4.2 on 2023-05-01\n",
                         b"/* @generated */\n",
                         b"<!-- This file was generated by a tool -->\n",
                         b"# -*- coding: utf-8 -*-\n# auto-generated file\n"):
            self.assertTrue(generated_reason("x.py", cabecera), cabecera)

    def test_merely_mentioning_the_word_is_not_generated(self):
        """Le pasó a analytics.py: su documentación habla de «cabeceras
        @generated» y se marcaba a sí mismo como generado."""
        doc = (b'# -*- coding: utf-8 -*-\n"""Analiza cosas.\n\n'
               b"  * separa lo marcado con @generated o DO NOT EDIT\n"
               b'"""\nREGEX = r"@generated|DO NOT EDIT"\n')
        self.assertEqual(generated_reason("analytics.py", doc), "")

    def test_minified(self):
        self.assertIn("minificado",
                      generated_reason("app.js", b"x", avg_line=900,
                                       size=50000))
        # Un archivo pequeño con líneas largas no basta.
        self.assertEqual(generated_reason("a.js", b"x", avg_line=900,
                                          size=500), "")


class DuplicatesTests(unittest.TestCase):

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def item(self, rel, data, known=False):
        p = write(self.tmp, rel, data)
        if known:
            return (rel, str(p), len(data), analytics._digest(data[:HEAD_BYTES]),
                    analytics._digest(data))
        return (rel, str(p), len(data), None, None)

    def test_identical_small_and_large_files(self):
        grande = os.urandom(HEAD_BYTES * 3)
        items = [self.item("a.bin", b"hola mundo"), self.item("b.bin", b"hola mundo"),
                 self.item("c.bin", grande), self.item("d/c.bin", grande),
                 self.item("unico.bin", b"otra cosa")]
        grupos = find_duplicates(items)
        self.assertEqual(sorted(g.paths for g in grupos),
                         [["a.bin", "b.bin"], ["c.bin", "d/c.bin"]])
        # Orden: primero lo que más espacio desperdicia.
        self.assertEqual(grupos[0].paths, ["c.bin", "d/c.bin"])
        self.assertEqual(grupos[0].wasted, len(grande))

    def test_same_head_different_tail_is_not_a_duplicate(self):
        base = os.urandom(HEAD_BYTES + 100)
        otro = base[:-1] + bytes([base[-1] ^ 0xFF])
        grupos = find_duplicates([self.item("x", base), self.item("y", otro)])
        self.assertEqual(grupos, [])

    def test_known_and_streamed_hashes_agree(self):
        datos = os.urandom(HEAD_BYTES * 2 + 7)
        grupos = find_duplicates([self.item("leido", datos, known=True),
                                  self.item("sin_leer", datos)])
        self.assertEqual([g.paths for g in grupos], [["leido", "sin_leer"]])

    def test_empty_files_are_not_reported(self):
        self.assertEqual(find_duplicates([self.item("a", b""),
                                          self.item("b", b"")]), [])

    @unittest.skipUnless(hasattr(os, "mkfifo"), "sin tuberías con nombre")
    def test_a_link_to_a_pipe_never_hangs_the_analysis(self):
        """Un enlace del proyecto a una tubería (o a /dev/tty) con el
        mismo tamaño que otro archivo: al buscar duplicados se abría
        siguiendo el enlace y el análisis esperaba para siempre."""
        tuberia = self.tmp / "tuberia"
        os.mkfifo(str(tuberia))
        proj = self.tmp / "proj"
        proj.mkdir()
        # «.png»: binario por extensión, se compara leyendo del disco.
        os.symlink(str(tuberia), str(proj / "imagen.png"))
        write(proj, "mismo.png", b"x" * len(str(tuberia)))
        fuera = self.tmp / "secreto.bin"
        fuera.write_bytes(b"y" * 40)
        os.symlink(str(fuera), str(proj / "otro.png"))
        write(proj, "igual.png", b"y" * 40)
        resultado = {}
        hilo = threading.Thread(target=lambda: resultado.update(
            r=analyze_project(proj, use_git=False, history=False)),
            daemon=True)
        hilo.start()
        hilo.join(20)
        self.assertFalse(hilo.is_alive(), "el análisis se quedó colgado")
        # Ni siquiera el enlace a un archivo de fuera cuenta como copia
        # de un archivo del proyecto: no se sigue.
        self.assertEqual(resultado["r"].duplicates, [])


class AnalyzeProjectTests(unittest.TestCase):

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.proj = self.tmp / "demo"
        write(self.proj, "src/app.py",
              '"""Módulo."""\n\nimport os  # sistema\n\n'
              "def f():\n    # TODO: quitar esto\n    return 1\n")
        write(self.proj, "src/util.js", "// a\nconst x = 1;\n/* b */\n")
        write(self.proj, "README.md", "# Demo\n\nTexto.\n")
        write(self.proj, "data/a.json", '{"a": 1}\n')
        write(self.proj, "data/b.json", '{"a": 1}\n')       # duplicado
        write(self.proj, "node_modules/lib/i.js", "var y=2;\n// FIXME no\n")
        write(self.proj, "img/logo.png", b"\x89PNG\r\n\x1a\n" + b"\x00" * 50)
        write(self.proj, "vacio.txt", b"")
        write(self.proj, "secreto/clave.env", "TOKEN=x\n")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def analyze(self, **kw):
        kw.setdefault("history", False)
        return analyze_project(self.proj, **kw)

    def test_languages_and_line_classes(self):
        rep = self.analyze()
        por_nombre = {l.name: l for l in rep.languages}
        py = por_nombre["Python"]
        # docstring + «# TODO» = 2 de comentario; «import os  # …» es código.
        self.assertEqual((py.files, py.code, py.comment, py.blank),
                         (1, 3, 2, 2))
        js = por_nombre["JavaScript"]
        self.assertEqual((js.code, js.comment, js.blank), (1, 2, 0))
        self.assertIn("Markdown", por_nombre)

    def test_generated_code_is_kept_apart(self):
        rep = self.analyze()
        generados = [f.rel for f in rep.generated_files()]
        self.assertEqual(generados, ["node_modules/lib/i.js"])
        propios = {l.name: l.code for l in rep.languages}
        self.assertEqual(propios["JavaScript"], 1)     # sin node_modules
        gen = {l.name: l.code for l in rep.generated_languages}
        self.assertEqual(gen["JavaScript"], 1)

    def test_markers_skip_generated_code_and_carry_the_line(self):
        rep = self.analyze()
        self.assertEqual(rep.markers, {"TODO": 1})        # el FIXME es ajeno
        m = rep.marker_samples[0]
        self.assertEqual((m.rel, m.line, m.kind), ("src/app.py", 6, "TODO"))
        self.assertEqual(m.text, "quitar esto")

    def test_duplicates_binaries_and_histogram(self):
        rep = self.analyze()
        self.assertEqual([g.paths for g in rep.duplicates],
                         [["data/a.json", "data/b.json"]])
        self.assertEqual(rep.binary_groups[0][0], "Imágenes")
        self.assertEqual(sum(n for _, n, _ in rep.histogram),
                         rep.total_files)
        self.assertEqual(sum(b for _, _, b in rep.histogram),
                         rep.total_bytes)
        self.assertEqual(rep.histogram[0][:2], ("vacíos", 1))

    def test_ignored_files_are_not_counted(self):
        rep = self.analyze(extra_patterns=["secreto/", "**/*.json"])
        rels = {f.rel for f in rep.files}
        self.assertNotIn("secreto/clave.env", rels)
        self.assertNotIn("data/a.json", rels)
        # Los dos JSON; la carpeta «secreto/» se poda entera sin abrirla.
        self.assertEqual(rep.ignored, 2)

    def test_files_too_large_are_noted_not_hidden(self):
        write(self.proj, "enorme.log", b"linea\n" * 2000)
        rep = self.analyze(max_file_bytes=1000)
        nota = [f for f in rep.files if f.rel == "enorme.log"][0].note
        self.assertIn("demasiado grande", nota)
        self.assertIn(nota, [f.note for f in rep.unreadable()])

    def test_progress_and_cancel(self):
        vistos = []
        self.analyze(on_progress=lambda h, t, rel: vistos.append((h, t)))
        self.assertTrue(vistos)
        self.assertEqual(vistos[-1][0], vistos[-1][1])     # llega al final
        parar = threading.Event()
        parar.set()
        with self.assertRaises(Cancelled):
            self.analyze(cancel=parar)

    def test_report_is_json_serializable_and_complete(self):
        rep = self.analyze()
        d = json.loads(json.dumps(rep.to_dict()))
        self.assertEqual(d["files"], rep.total_files)
        self.assertEqual(len(d["file_list"]), rep.total_files)
        self.assertIsNone(d["git"])
        sin = rep.to_dict(include_files=False)
        self.assertNotIn("file_list", sin)

    def test_summary_text_keeps_its_commas(self):
        """Los miles llevan punto, pero las comas de las frases siguen
        siendo comas (se rompió una vez al formatear la frase entera)."""
        rep = self.analyze()
        lineas = summary_lines(rep)
        self.assertIn("líneas de código, ", lineas[1])
        vacio = Path(self.tmp) / "vacio"
        vacio.mkdir()
        self.assertTrue(summary_lines(analyze_project(vacio, history=False)))

    def test_utf16_files_are_text(self):
        write(self.proj, "script.ps1",
              "# comentario\nWrite-Host 1\n".encode("utf-16"))
        rep = self.analyze()
        f = [x for x in rep.files if x.rel == "script.ps1"][0]
        self.assertEqual((f.language, f.code, f.comment), ("PowerShell", 1, 1))


